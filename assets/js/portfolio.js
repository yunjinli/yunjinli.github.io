// Optional motion only: every section and link works without JavaScript.
(function () {
  "use strict";

  var reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
  var navigation = document.querySelector(".portfolio-nav-links");
  if (!navigation) return;

  var links = Array.from(navigation.querySelectorAll('a[href^="#"]'));
  var sections = links.map(function (link) {
    return document.querySelector(link.getAttribute("href"));
  });

  // Native anchors retain their hashes, browser history, and keyboard behavior.
  // Smooth scrolling is an enhancement, scoped to this page.
  var scrollStyle = document.createElement("style");
  scrollStyle.textContent = "@media (prefers-reduced-motion: no-preference) { html { scroll-behavior: smooth; } }";
  document.head.appendChild(scrollStyle);

  var scheduled = false;
  function updateNavigation() {
    var active = 0;
    sections.forEach(function (section, index) {
      if (section && section.getBoundingClientRect().top <= 150) active = index;
    });
    // A short final section may hit the end of the page before reaching the header.
    if (window.scrollY > 0 && window.scrollY + window.innerHeight >= document.documentElement.scrollHeight - 2) {
      active = links.length - 1;
    }
    links.forEach(function (link, index) {
      if (index === active) link.setAttribute("aria-current", "location");
      else link.removeAttribute("aria-current");
    });
    scheduled = false;
  }
  window.addEventListener(
    "scroll",
    function () {
      if (!scheduled) {
        scheduled = true;
        window.requestAnimationFrame(updateNavigation);
      }
    },
    { passive: true }
  );
  window.addEventListener("resize", updateNavigation);
  updateNavigation();

  // Abstracts occupy the full card width. Without JS, their text stays readable.
  document.querySelectorAll(".publication-abstract-toggle").forEach(function (button) {
    var panel = document.getElementById(button.getAttribute("aria-controls"));
    if (!panel) return;

    function setOpen(open) {
      button.setAttribute("aria-expanded", String(open));
      panel.classList.toggle("is-open", open);
      panel.setAttribute("aria-hidden", String(!open));
      panel.inert = !open;
    }

    panel.classList.add("is-collapsible");
    setOpen(false);
    button.hidden = false;
    button.addEventListener("click", function () {
      setOpen(button.getAttribute("aria-expanded") !== "true");
    });
  });

  // The bibliography's outer cards are generated by Jekyll Scholar.
  var revealObserver;
  document.querySelectorAll(".portfolio-research ol.bibliography > li, .portfolio-project").forEach(function (card) {
    card.dataset.reveal = "card";
  });

  // Render each item once. Without JS, the complete lists remain available.
  var expandedSections = {};
  document.querySelectorAll("[data-expandable]").forEach(function (section) {
    var kind = section.dataset.expandable;
    var button = section.querySelector(".portfolio-expand");
    var heading = section.querySelector("h2");
    var originalHeading = heading.textContent;
    var fullHeading = { news: "News", publications: "Publications", projects: "Projects" }[kind];
    var items;
    var extras;

    if (kind === "news") {
      items = Array.from(section.querySelectorAll("tbody > tr"));
      var limit = Number(section.dataset.previewLimit);
      extras = limit > 0 ? items.slice(limit) : [];
    } else if (kind === "projects") {
      items = Array.from(section.querySelectorAll(".portfolio-project"));
      extras = items.filter(function (item) {
        return item.dataset.portfolioSelected !== "true";
      });
    } else {
      items = Array.from(section.querySelectorAll("ol.bibliography > li"));
      extras = items.filter(function (item) {
        var entry = item.querySelector("[data-publication-selected]");
        return !entry || entry.dataset.publicationSelected !== "true";
      });
    }

    function setExpanded(expanded, animate) {
      extras.forEach(function (item) {
        item.hidden = !expanded;
        if (!expanded)
          item.querySelectorAll("video").forEach(function (video) {
            video.pause();
          });
        if (item.dataset.reveal === "card") {
          // Expanded cards enter as they reach the viewport, including those below the fold.
          if (!expanded) {
            item.classList.remove("is-visible");
            if (revealObserver) revealObserver.observe(item);
          }
        } else if (expanded && animate && !reducedMotion.matches && item.animate) {
          item.animate(
            [
              { opacity: 0, transform: "translateY(6px)" },
              { opacity: 1, transform: "translateY(0)" },
            ],
            { duration: 220, easing: "ease-out" }
          );
        }
      });
      button.setAttribute("aria-expanded", String(expanded));
      button.textContent = expanded ? "Show less " : button.dataset.label + " (" + items.length + ") ";
      var arrow = document.createElement("span");
      arrow.setAttribute("aria-hidden", "true");
      arrow.textContent = expanded ? "↑" : "↓";
      button.appendChild(arrow);
      heading.textContent = expanded ? fullHeading : originalHeading;
      updateNavigation();
    }

    expandedSections["#all-" + kind] = function () {
      if (extras.length) setExpanded(true, false);
      section.scrollIntoView({ block: "start" });
    };
    if (!extras.length) {
      heading.textContent = fullHeading;
      return;
    }

    button.hidden = false;
    setExpanded(false, false);
    button.addEventListener("click", function () {
      var expanded = button.getAttribute("aria-expanded") !== "true";
      setExpanded(expanded, true);
      // Keep copied URLs consistent with the visible view, without adding history entries.
      var hash = expanded ? "#all-" + kind : "#" + section.id;
      window.history.replaceState(null, "", window.location.pathname + window.location.search + hash);
    });
  });

  function openLinkedSection() {
    var expand = expandedSections[window.location.hash];
    if (expand) window.requestAnimationFrame(expand);
  }
  window.addEventListener("hashchange", openLinkedSection);
  openLinkedSection();

  // Native buttons keep repository counts consistent with the other paper links.
  // If GitHub is unavailable, each button remains a working GitHub link.
  var repositories = new Map();
  document.querySelectorAll("[data-github-repo]").forEach(function (button) {
    var repository = button.dataset.githubRepo;
    if (!/^[\w.-]+\/[\w.-]+$/.test(repository)) return;
    if (!repositories.has(repository)) repositories.set(repository, []);
    repositories.get(repository).push(button);
  });
  repositories.forEach(function (buttons, repository) {
    function showStars(count) {
      if (!Number.isInteger(count) || count < 0) return;
      buttons.forEach(function (button) {
        button.querySelector("[data-star-label]").textContent = count.toLocaleString() + (count === 1 ? " star" : " stars");
        button.setAttribute("aria-label", count + " GitHub stars for " + repository);
      });
    }

    var cacheKey = "portfolio-stars:" + repository;
    try {
      var cached = JSON.parse(sessionStorage.getItem(cacheKey));
      if (cached && Number.isInteger(cached.count) && cached.count >= 0 && Date.now() - cached.checkedAt < 3600000) {
        showStars(cached.count);
        return;
      }
    } catch (_) {
      /* Storage may be disabled; the links still work. */
    }

    var controller = new AbortController();
    var timeout = window.setTimeout(function () {
      controller.abort();
    }, 5000);
    fetch("https://api.github.com/repos/" + repository, { signal: controller.signal })
      .then(function (response) {
        if (!response.ok) throw new Error("GitHub count unavailable");
        return response.json();
      })
      .then(function (data) {
        if (!Number.isInteger(data.stargazers_count) || data.stargazers_count < 0) return;
        showStars(data.stargazers_count);
        try {
          sessionStorage.setItem(cacheKey, JSON.stringify({ count: data.stargazers_count, checkedAt: Date.now() }));
        } catch (_) {
          /* No persistent storage is required. */
        }
      })
      .catch(function () {
        /* Leave the plain GitHub link when the count is unavailable. */
      })
      .finally(function () {
        window.clearTimeout(timeout);
      });
  });

  // Hugging Face's downloads field is monthly; request downloadsAllTime explicitly.
  var datasets = new Map();
  document.querySelectorAll("[data-hf-dataset]").forEach(function (button) {
    var dataset = button.dataset.hfDataset;
    if (!/^[\w.-]+\/[\w.-]+$/.test(dataset)) return;
    if (!datasets.has(dataset)) datasets.set(dataset, []);
    datasets.get(dataset).push(button);
  });
  datasets.forEach(function (buttons, dataset) {
    function showDownloads(count) {
      buttons.forEach(function (button) {
        var label = count.toLocaleString() + (count === 1 ? " download" : " downloads");
        button.querySelector("[data-download-label]").textContent = "Dataset · " + label;
        button.title = label + " all time on Hugging Face";
        button.setAttribute("aria-label", dataset + ": " + label + " all time on Hugging Face");
      });
    }

    var cacheKey = "portfolio-hf-downloads-all-time:" + dataset;
    try {
      var cached = JSON.parse(sessionStorage.getItem(cacheKey));
      if (cached && Number.isSafeInteger(cached.count) && cached.count >= 0) {
        showDownloads(cached.count);
        if (Date.now() - cached.checkedAt < 3600000) return;
      }
    } catch (_) {
      /* Storage is optional; the dataset link remains available. */
    }

    var controller = new AbortController();
    var timeout = window.setTimeout(function () {
      controller.abort();
    }, 5000);
    fetch("https://huggingface.co/api/datasets/" + dataset + "?expand=downloadsAllTime", { signal: controller.signal })
      .then(function (response) {
        if (!response.ok) throw new Error("Dataset downloads unavailable");
        return response.json();
      })
      .then(function (data) {
        if (data.id !== dataset || !Number.isSafeInteger(data.downloadsAllTime) || data.downloadsAllTime < 0) return;
        showDownloads(data.downloadsAllTime);
        try {
          sessionStorage.setItem(cacheKey, JSON.stringify({ count: data.downloadsAllTime, checkedAt: Date.now() }));
        } catch (_) {
          /* No persistent storage is required. */
        }
      })
      .catch(function () {
        /* Keep the last known total, or the plain dataset link, on failure. */
      })
      .finally(function () {
        window.clearTimeout(timeout);
      });
  });

  if ("IntersectionObserver" in window) {
    // Reset only after a card is completely offscreen, with a little extra room
    // so small scroll adjustments cannot repeatedly restart its entrance.
    var cardExitObserver = new IntersectionObserver(
      function (entries) {
        entries.forEach(function (entry) {
          if (!entry.isIntersecting) entry.target.classList.remove("is-visible");
        });
      },
      { rootMargin: "80px 0px", threshold: 0 }
    );

    revealObserver = new IntersectionObserver(
      function (entries) {
        var rowTop = null;
        var column = 0;
        var entering = entries.filter(function (entry) {
          return entry.isIntersecting && entry.intersectionRatio >= 0.15 && !entry.target.classList.contains("is-visible");
        });
        entering.sort(function (a, b) {
          return a.boundingClientRect.top - b.boundingClientRect.top || a.boundingClientRect.left - b.boundingClientRect.left;
        });
        entering.forEach(function (entry) {
          if (!reducedMotion.matches) {
            if (entry.target.dataset.reveal === "card") {
              var top = entry.boundingClientRect.top;
              // Only stagger cards sharing a row; stacked mobile cards start immediately.
              column = rowTop !== null && Math.abs(top - rowTop) < 16 ? column + 1 : 0;
              rowTop = top;
              entry.target.style.setProperty("--reveal-delay", Math.min(column * 100, 200) + "ms");
            }
          }
          entry.target.classList.add("is-visible");
          if (entry.target.dataset.reveal !== "card") revealObserver.unobserve(entry.target);
        });
      },
      { threshold: [0, 0.15], rootMargin: "0px 0px -64px 0px" }
    );
    document.querySelectorAll("[data-reveal]").forEach(function (element) {
      if (element.dataset.reveal === "card") {
        // Only prepare cards after both observers exist. Without JS or observer
        // support, the original content remains visible and usable.
        element.classList.add("reveal-ready");
        cardExitObserver.observe(element);
      }
      revealObserver.observe(element);
    });
  }

  var hoverPointer = window.matchMedia("(hover: hover) and (pointer: fine)");
  document.querySelectorAll(".portfolio-project video").forEach(function (video) {
    var previewing = false;
    var userControlled = false;
    // Once someone uses the native controls, leave playback up to them.
    video.addEventListener("pointerdown", function () {
      userControlled = true;
    });
    video.addEventListener("keydown", function () {
      userControlled = true;
    });
    video.closest(".portfolio-project").addEventListener("pointerenter", function () {
      if (userControlled || reducedMotion.matches || !hoverPointer.matches || !video.paused) return;
      previewing = true;
      var play = video.play();
      if (play)
        play.catch(function () {
          previewing = false;
        });
    });
    video.closest(".portfolio-project").addEventListener("pointerleave", function () {
      if (previewing && !userControlled) video.pause();
      previewing = false;
    });
    reducedMotion.addEventListener("change", function () {
      if (reducedMotion.matches && previewing && !userControlled) {
        video.pause();
        previewing = false;
      }
    });
  });
})();
